-- Começa com catálogo vazio. Leitura pública; alterações ficam bloqueadas
-- até configurar autenticação e políticas administrativas.
create table if not exists public.objetos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text not null,
  local_encontrado text not null default '',
  descricao text not null default '',
  imagem_url text,
  status text not null default 'open' check (status in ('open','returned')),
  data_encontrado date,
  criado_em timestamptz not null default now()
);

alter table public.objetos enable row level security;

drop policy if exists "Leitura pública do catálogo" on public.objetos;
create policy "Leitura pública do catálogo"
on public.objetos for select to anon, authenticated using (true);

